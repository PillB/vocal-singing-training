  const I18n = {
    lang: "es",
    strings: STRINGS,
    t(key, vars) {
      const table = this.strings[this.lang] || this.strings.es;
      let s = table[key] ?? this.strings.en[key] ?? this.strings.es[key] ?? key;
      if (vars) {
        Object.keys(vars).forEach((k) => {
          s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(vars[k]));
        });
      }
      return s;
    },
    exTitle(ex) {
      if (!ex) return "";
      const key = "ex." + ex.id;
      const tr = this.t(key);
      return tr === key ? ex.title : tr;
    },
    /**
     * Locale-aware exercise guide field (steps, tips, mistakes, original, research).
     * Spanish: VT_EXERCISE_LOCALE_ES[id] or *Es fields on the exercise object.
     */
    exField(ex, field) {
      if (!ex || !field) return field === "steps" || field === "tips" || field === "mistakes" ? [] : "";
      const isEs = this.lang === "es";
      if (isEs) {
        const pack = (global.VT_EXERCISE_LOCALE_ES || {})[ex.id];
        if (pack && pack[field] != null) return pack[field];
        const esKey = field + "Es";
        if (ex[esKey] != null) return ex[esKey];
      }
      const v = ex[field];
      if (field === "steps" || field === "tips" || field === "mistakes") {
        return Array.isArray(v) ? v : [];
      }
      return v == null ? "" : v;
    },
    setLang(lang) {
      this.lang = lang === "en" ? "en" : "es";
      try {
        localStorage.setItem("vt_lang", this.lang);
      } catch {
        /* ignore */
      }
      document.documentElement.lang = this.lang === "es" ? "es" : "en";
      this.applyDom();
      if (typeof this.onChange === "function") this.onChange(this.lang);
    },
    init() {
      let saved = "es";
      try {
        saved = localStorage.getItem("vt_lang") || "es";
      } catch {
        /* ignore */
      }
      this.lang = saved === "en" ? "en" : "es";
      document.documentElement.lang = this.lang === "es" ? "es" : "en";
      this.applyDom();
    },
    applyDom() {
      document.querySelectorAll("[data-i18n]").forEach((el) => {
        const key = el.getAttribute("data-i18n");
        if (!key) return;
        const val = this.t(key);
        if (el.tagName === "OPTION") {
          el.textContent = val;
        } else if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
          if (el.hasAttribute("data-i18n-placeholder")) el.placeholder = val;
        } else if (el.hasAttribute("data-i18n-html")) {
          el.innerHTML = val;
        } else {
          el.textContent = val;
        }
      });
      document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (key) el.placeholder = this.t(key);
      });
      document.querySelectorAll("[data-i18n-title]").forEach((el) => {
        const key = el.getAttribute("data-i18n-title");
        if (key) el.title = this.t(key);
      });
      // data-i18n-aria was in the markup from the start but never had an
      // applier, so five landmark and tab labels — the section nav, the two
      // track tabs and the breadcrumb — stayed Spanish in the English UI.
      document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
        const key = el.getAttribute("data-i18n-aria");
        if (key) el.setAttribute("aria-label", this.t(key));
      });
      const title = this.t("meta.title");
      if (title) document.title = title;
      const meta = document.querySelector('meta[name="description"]');
      if (meta) meta.setAttribute("content", this.t("meta.desc"));
      const langBtn = document.getElementById("btn-lang");
      if (langBtn) langBtn.textContent = this.t("nav.lang");
    }
  };

  global.VTI18n = I18n;
  global.t = (k, v) => I18n.t(k, v);
