/**
 * Money going back, on the Stripe side.
 *
 * Mercado Pago has always ended the access a refunded or charged-back payment
 * paid for; Stripe did not, so the same product behaved differently depending
 * on which rail somebody bought on, and a refunded yearly pass kept up to 366
 * days of Pro (QA round 4, QA-W-02). The README's stated reason was that a
 * charge carries nothing a license can be found by. That is true of the charge
 * alone and false of the pair: a one-time checkout names its payment intent,
 * and so does the refunded charge and the dispute.
 *
 * What these tests pin is the pairing and its edges, because every one of them
 * is a way to take access from somebody who still paid for it, or to leave it
 * with somebody who did not:
 *   - a full refund ends the access that charge paid for;
 *   - a partial refund does not, because it is a goodwill gesture;
 *   - a chargeback ends it the day it is opened;
 *   - the refund of an earlier month leaves a later month alone;
 *   - a refund naming a payment we have never seen mints nothing, and is
 *     retried for a day in case it simply arrived first;
 *   - and the payment index is not a second way into /v1/claim.
 *
 * Everything runs through the real router and the real signature check.
 */

import assert from "node:assert/strict";
import { createHmac } from "node:crypto";
import test from "node:test";

import { handleRequest } from "../src/index.js";
import { HANDLED_EVENT_TYPES } from "../src/stripe.js";
import { PAYMENT_TTL_SECONDS } from "../src/store.js";
import { createFakeKv, createTestEnv } from "./fixtures.mjs";

const DAY = 86400;
/** The worker's monthly interval, written out rather than imported. */
const MONTH = 31 * DAY;
const T = Math.floor(Date.now() / 1000);

const hmacHex = (secret, message) => createHmac("sha256", secret).update(message).digest("hex");

/** A fresh env with its own KV, so no test can see another's keys. */
const freshEnv = () => createTestEnv({ ENTITLEMENTS: createFakeKv() });

/**
 * Deliver one signed Stripe event to the real webhook route.
 * @param {Object} env Worker env.
 * @param {string} id Event id.
 * @param {string} type Event type.
 * @param {number} atDays Days after T the event was emitted.
 * @param {Object} object The event's data object.
 * @param {{now?: number}} [options] Router injectables.
 * @returns {Promise<Response>} The worker's answer.
 */
function deliver(env, id, type, atDays, object, options) {
  const raw = JSON.stringify({ id, type, created: T + atDays * DAY, data: { object } });
  const ts = Math.floor(Date.now() / 1000);
  const request = new Request("https://w.test/v1/webhooks/stripe", {
    method: "POST",
    body: raw,
    headers: { "Stripe-Signature": `t=${ts},v1=${hmacHex(env.STRIPE_WEBHOOK_SECRET, `${ts}.${raw}`)}` }
  });
  return handleRequest(request, env, options);
}

/**
 * Ask /v1/claim for a session, as the browser does, on a given day.
 * @param {Object} env Worker env.
 * @param {string} sessionId Checkout session id (or anything to try).
 * @param {number} atDays Days after T to pretend it is.
 * @returns {Promise<{status: number, body: Object}>} Status and parsed body.
 */
async function claim(env, sessionId, atDays) {
  const real = Date.now;
  Date.now = () => (T + atDays * DAY) * 1000;
  try {
    const response = await handleRequest(
      new Request("https://w.test/v1/claim", {
        method: "POST",
        body: JSON.stringify({ provider: "stripe", sessionId }),
        headers: { "content-type": "application/json" }
      }),
      env
    );
    return { status: response.status, body: await response.json() };
  } finally {
    Date.now = real;
  }
}

/** A paid one-time checkout for the yearly pass, with its payment intent. */
const pass = (sessionId, paymentIntent) => ({
  id: sessionId,
  mode: "payment",
  customer: "cus_r",
  payment_intent: paymentIntent,
  payment_status: "paid",
  metadata: { plan: "pro_yearly" }
});

test("the three events that carry money going back are in the list an operator subscribes to", () => {
  // The README's table and the `stripe listen --events` line are generated by
  // hand from this list. A handler the endpoint does not subscribe to never
  // runs, so this is the difference between a fix and a fix nobody receives.
  for (const type of ["charge.refunded", "charge.dispute.created", "charge.dispute.funds_withdrawn"]) {
    assert.equal(HANDLED_EVENT_TYPES.includes(type), true, type);
  }
});

test("a yearly pass refunded in full stops being Pro, and the payment index is what found it", async () => {
  const env = freshEnv();
  await deliver(env, "e1", "checkout.session.completed", 0, pass("cs_full", "pi_full"));
  assert.equal((await claim(env, "cs_full", 1)).status, 200, "control: paid, so entitled");
  // The payment was written down against the license when it was first seen,
  // which is the only reason the refund below can find anything.
  const indexed = await env.ENTITLEMENTS.get("pay:stripe:pi_full");
  assert.equal(typeof indexed, "string");
  assert.ok(indexed.length > 0);
  assert.equal(
    env.ENTITLEMENTS.ttlOf("pay:stripe:pi_full"),
    PAYMENT_TTL_SECONDS,
    "it has to outlive the year it bought plus the dispute window"
  );

  await deliver(env, "e2", "charge.refunded", 2, {
    id: "ch_full",
    created: T,
    customer: "cus_r",
    payment_intent: "pi_full",
    refunded: true,
    amount: 5000,
    amount_refunded: 5000
  });
  const after = await claim(env, "cs_full", 3);
  assert.notEqual(after.status, 200, "refunded on day 2, so not Pro on day 3");
  // And still not, a year later: the period ended, it did not pause.
  assert.notEqual((await claim(env, "cs_full", 300)).status, 200);
});

test("a partial refund is a goodwill gesture, not the end of what was bought", async () => {
  const env = freshEnv();
  await deliver(env, "e1", "checkout.session.completed", 0, pass("cs_part", "pi_part"));
  const answer = await deliver(env, "e2", "charge.refunded", 2, {
    id: "ch_part",
    created: T,
    customer: "cus_r",
    payment_intent: "pi_part",
    refunded: false,
    amount: 5000,
    amount_refunded: 1000
  });
  assert.equal(answer.status, 200, "acknowledged, so Stripe stops");
  assert.equal((await answer.json()).reason, "partial_refund");
  assert.equal((await claim(env, "cs_part", 3)).status, 200, "a fifth back is not access gone");
  assert.equal(await env.ENTITLEMENTS.get("reversed:stripe"), null);
  assert.equal(
    [...env.ENTITLEMENTS.store.keys()].filter((k) => k.startsWith("reversed:")).length,
    0,
    "nothing was recorded as reversed"
  );
});

test("a chargeback ends access the day it is opened, not the day it is lost", async () => {
  const env = freshEnv();
  await deliver(env, "e1", "checkout.session.completed", 0, pass("cs_dis", "pi_dis"));
  assert.equal((await claim(env, "cs_dis", 1)).status, 200);
  // A dispute names its payment intent but never says when the payment was
  // taken, so it reverses whichever charge the license last counted.
  await deliver(env, "e2", "charge.dispute.created", 5, {
    id: "du_dis",
    charge: "ch_dis",
    payment_intent: "pi_dis",
    amount: 5000,
    status: "needs_response",
    created: T + 5 * DAY
  });
  assert.notEqual((await claim(env, "cs_dis", 6)).status, 200, "not Pro the day after it was opened");
});

test("funds withdrawn on a dispute we never saw opened ends it too", async () => {
  const env = freshEnv();
  await deliver(env, "e1", "checkout.session.completed", 0, pass("cs_fw", "pi_fw"));
  await deliver(env, "e2", "charge.dispute.funds_withdrawn", 5, {
    id: "du_fw",
    charge: "ch_fw",
    payment_intent: "pi_fw",
    status: "lost"
  });
  assert.notEqual((await claim(env, "cs_fw", 6)).status, 200);
});

test("the refund of an earlier month leaves a later month's access alone", async () => {
  const env = freshEnv();
  // A subscription, and two renewals on an API version that still names the
  // invoice's payment intent — which is the only way a renewal's payment is
  // ever seen before its refund (see paymentIdForInvoice).
  await deliver(env, "e1", "checkout.session.completed", 0, {
    id: "cs_sub",
    mode: "subscription",
    customer: "cus_s",
    subscription: "sub_s",
    payment_status: "paid"
  });
  const invoice = (id, paymentIntent, endDays) => ({
    id,
    customer: "cus_s",
    subscription: "sub_s",
    payment_intent: paymentIntent,
    lines: { data: [{ period: { start: T + endDays * DAY - MONTH, end: T + endDays * DAY } }] }
  });
  await deliver(env, "e2", "invoice.paid", 0, invoice("in_1", "pi_m1", 31));
  await deliver(env, "e3", "invoice.paid", 31, invoice("in_2", "pi_m2", 62));
  assert.equal((await claim(env, "cs_sub", 40)).status, 200, "control: the second month is paid");

  // Month one is refunded. Month two paid for the period the customer is in,
  // so access stays.
  await deliver(env, "e4", "charge.refunded", 35, {
    id: "ch_m1",
    created: T,
    customer: "cus_s",
    payment_intent: "pi_m1",
    refunded: true,
    amount: 1900,
    amount_refunded: 1900
  });
  assert.equal((await claim(env, "cs_sub", 40)).status, 200, "the refund of month one is not the end of month two");

  // Month two is refunded as well: that one did pay for where they are.
  await deliver(env, "e5", "charge.refunded", 40, {
    id: "ch_m2",
    created: T + 31 * DAY,
    customer: "cus_s",
    payment_intent: "pi_m2",
    refunded: true,
    amount: 1900,
    amount_refunded: 1900
  });
  assert.notEqual((await claim(env, "cs_sub", 41)).status, 200, "now there is nothing paid for");
});

test("a refund for a payment this worker never saw mints nothing, and is retried for a day", async () => {
  const env = freshEnv();
  const charge = {
    id: "ch_ghost",
    created: T,
    customer: "cus_ghost",
    payment_intent: "pi_ghost",
    refunded: true,
    amount: 5000,
    amount_refunded: 5000
  };
  // It may be a payment taken on the same Stripe account by something else
  // entirely — or it may be a delivery that overtook the checkout that paid.
  // So: retried, for the same day a Mercado Pago resource its API has not
  // caught up on is retried.
  const first = await deliver(env, "e1", "charge.refunded", 2, charge, { now: T });
  assert.equal(first.status, 500);
  assert.equal((await first.json()).reason, "unknown_license");
  const stillWaiting = await deliver(env, "e1", "charge.refunded", 2, charge, { now: T + 3600 });
  assert.equal(stillWaiting.status, 500, "an hour in, still worth retrying");

  const givenUp = await deliver(env, "e1", "charge.refunded", 2, charge, { now: T + DAY + 1 });
  assert.equal(givenUp.status, 200, "a day on, acknowledged so Stripe stops");
  assert.equal((await givenUp.json()).reason, "unknown_license");

  // Whatever the answer, no license and no index entry was invented for it.
  const keys = [...env.ENTITLEMENTS.store.keys()];
  assert.deepEqual(keys.filter((k) => k.startsWith("lic:")), []);
  assert.deepEqual(keys.filter((k) => k.startsWith("pay:")), []);
});

test("a payment intent is not a second way into /v1/claim", async () => {
  const env = freshEnv();
  await deliver(env, "e1", "checkout.session.completed", 0, pass("cs_sep", "pi_sep"));
  // The session id is what the browser is handed and what it may claim with.
  assert.equal((await claim(env, "cs_sep", 1)).status, 200);
  // The payment intent is an internal id that the refund path reads. Keeping
  // it in its own key space rather than aliasing the claim index is the reason
  // it buys nobody a token.
  const byPayment = await claim(env, "pi_sep", 1);
  assert.notEqual(byPayment.status, 200);
  assert.equal(byPayment.body.reason, "pending");
});
